// The uid whose sockets get locked: 9router's own service user, never root.
// Locking uid 0 would also capture systemd, DHCP and root helpers, which is
// exactly the collateral damage this design must avoid — so a root (or empty)
// answer is a hard failure, not a fallback.
async function routerUid() {
  const override = (process.env.NINE_EGRESS_UID || "").trim();
  if (override) return override;
  const r = await sh(`systemctl show 9router -p User --value 2>/dev/null | tr -d '\\n'`, {
    check: false,
  });
  const user = r.out.trim();
  if (!user) {
    throw new Error(
      "9router.service has no User= — refusing to lock egress on uid 0 " +
        "(bootstrap.sh must install the unit with the dedicated user)",
    );
  }
  if (user === "root" || user === "0") {
    throw new Error(
      `9router runs as "${user}" — refusing the egress lock: root covers systemd, ` +
        "DHCP and the tunnel. Reinstall the unit as the dedicated user.",
    );
  }
  const id = await sh(`id -u ${user} 2>/dev/null || true`, { check: false });
  const uid = id.out.trim();
  if (!/^[0-9]+$/.test(uid) || uid === "0") {
    throw new Error(`cannot resolve a non-root uid for 9router's user "${user}"`);
  }
  return uid;
}

// redsocks turns the NAT redirect back into a SOCKS5 connection. It runs as its
// own user so the uid-scoped rule can never catch the redirector itself.
