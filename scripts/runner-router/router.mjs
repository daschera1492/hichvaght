// Runner-only 9Router: no Freestyle VM, no Tailscale exit node.
//
// Everything runs on the GitHub runner itself:
//
//   cloudflared  ──► 127.0.0.1:20128   the public entry for router2.codol.ir
//   9router      ──► systemd as the dedicated user "nine", state in /var/lib/9router
//   awmvpn-core  ──► SOCKS5 127.0.0.1:10810 (Mozilla free VPN)
//   socks-bridge ──► HTTP CONNECT 127.0.0.1:8118, forwarding into that SOCKS5
//
// Order is deliberate and enforced:
//
//   1. VPN comes up and its exit IP is proven BEFORE 9router is even installed.
//   2. 9router is installed but NOT started (bootstrap is called with
//      NINE_ROUTER_SKIP_START=1).
//   3. Its egress is locked at the kernel level: every TCP packet generated by
//      9router's uid is redirected into redsocks → the VPN's SOCKS5, and all
//      other protocols (except DNS) are dropped. The lock is fail-closed: if it
//      cannot be applied and proven, the start aborts and 9router never runs.
//   4. Only then is 9router started.
//
// The kernel lock is the guarantee; the app's own outbound-proxy setting
// (HTTPS_PROXY → the socks-bridge in socks-bridge.mjs) is kept as a second
// layer, and gives provider calls DNS-at-the-SOCKS5 (hostname CONNECT).
//
// The tunnel and the Actions agent run under their own uids, so they keep the
// runner's direct route (tunnelling the tunnel would turn any VPN blip into a
// dead domain).
//
// Usage: node router.mjs start | stop
//
// State still travels through the encrypted release asset, so the database the
// VM sessions archived is picked up unchanged.
